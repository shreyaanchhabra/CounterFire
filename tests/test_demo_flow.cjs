const assert=require('node:assert/strict');
const {nextAction}=require('../frontend/demo-flow.js');
const run=(v,extra={})=>nextAction(v,{busy:false,dirty:false,hasCopy:false,...extra}).action;
const base={mode:'fixture',status:'ready',round:0,branch_id:'main'};
assert.equal(run(null),'start');
assert.equal(run(base),'advance');
assert.equal(run({...base,round:1}),'advance');
assert.equal(run({...base,round:2,status:'awaiting_approval'}),'analyze');
const checked={...base,round:2,status:'awaiting_approval',analysis:{status:'done'},evidence:{source:'fixture'}};
assert.equal(run(checked),'draft');
const drafted={...checked,drafts:{framings:[{key:'B'}]}};
assert.equal(run(drafted),'propose');
const proposed={...drafted,pending_intervention:{revision:1,content_hash:'hash'}};
assert.equal(run(proposed,{hasCopy:true}),'approve');
assert.equal(run(proposed,{hasCopy:true,dirty:true}),'propose','Edited copy must never be approved through the old hash');
assert.equal(run({...proposed,status:'running'}),'wait');
assert.equal(run({...proposed,approval:{revision:1},status:'ready'}),'advance');
assert.equal(run({...base,round:4,status:'complete'}),'replay');
assert.equal(run({...base,round:2,branch_id:'branch-none'}),'advance');
assert.equal(run({...checked,mode:'replay',recorded_intervention:{text_en:'Recorded'}}),'propose');
assert.equal(run({...base,mode:'replay',round:2,recorded_intervention:null}),'advance');
assert.equal(run({...checked,analysis:{status:'error'}}),'analyze');
assert.equal(run({...base,status:'error'}),'start');
assert.equal(nextAction(null,{busy:true}).action,'wait');
assert.equal(nextAction(proposed,{busy:true}).phase,2,'Review stays visible while saving');
assert.equal(nextAction({...checked,status:'running',editor_status:{status:'running'}}).phase,2);
assert.equal(nextAction({...base,status:'running',analysis:{status:'running'}}).phase,1);

assert.equal(run(checked,{hasCopy:true}),'draft','Revised evidence needs fresh generated drafts in the guided flow');
console.log('Demo flow checks passed');
